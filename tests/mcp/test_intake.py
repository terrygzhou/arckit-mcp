"""Tests for the generated ``arckit_mcp.intake`` module (PR 2, task 2.x).

``arckit_mcp/intake.py`` is a generated data table (regenerated by
``scripts/generate-mcp-intake.py`` in the arc-kit repo — cross-repo
handoff, so it lands in arckit-mcp as a checked-in file with a
DO-NOT-EDIT header). This suite verifies its *shape and invariants*,
not its contents, so it keeps passing as templates gain or lose
intake questions between regenerations.

Covered:

* the module imports cleanly and exposes exactly the two documented
  top-level tables (``INTAKE``, ``COVERAGE``);
* ``INTAKE`` key/values are well-formed: 4-char uppercase doc-type
  codes, a non-empty list of non-empty string questions, optional
  ``mandatory_inputs`` restricted to 4-char uppercase codes, and a
  ``source`` path ending in ``.md``;
* ``COVERAGE`` is total: every known doc-type code carries a status
  of ``"covered"`` or ``"no-static-questions"``, and the
  ``"covered"`` set is exactly the ``INTAKE`` key set (no coverage
  drift between the two tables);
* the known generator quirk is pinned in place: for multi-option
  questions (template blocks that list choices after the question
  line), the option strings are appended to the same ``questions``
  list rather than being nested — so ``GAPS`` and ``TRANS`` carry
  option items interleaved with their questions. This is intentional
  (the MCP payload renders them as plain lines); the assertion is a
  tripwire so a "fix" that restructures the data fails here, not in
  production.

The suite does NOT assert exact question text, question counts, or
the 12/177 split — those shift with template edits. It DOES assert
the structural invariants above, plus the exact ``INTAKE`` key set
as a *minimum*: the current 12 codes must all remain present and
covered, even if more are added.
"""

from __future__ import annotations

import re

import pytest

from arckit_mcp.intake import COVERAGE, INTAKE

# Doc-type codes follow the doc-types.mjs registry: uppercase alphanumerics
# with optional hyphens, 2–9 chars (e.g. DR, NIS2, PRIN-COMP, JSP936).
_DOC_TYPE_RE = re.compile(r"^[A-Z0-9-]{2,9}$")

# Every code the current generator emits must stay covered. This is a
# minimum, not an exact set: adding intake questions to more templates
# only grows INTAKE and never removes these.
_MINIMUM_INTAKE_CODES = {
    "AAGI",  # AI agent inventory (arckit-agent-architecture)
    "APP",   # Application inventory (arckit-togaf-adm)
    "DISC",  # Discovery (arckit-togaf-adm)
    "GAPS",  # Gap analysis (arckit-togaf-adm)
    "ITVN",  # IT value network (arckit-it4it)
    "ITVS",  # IT value stream (arckit-it4it)
    "OAGOV", # OA governance (arckit-oaa)
    "OAPR",  # OA portfolio (arckit-oaa)
    "OASEC", # OA security (arckit-oaa)
    "OASTR", # OA strategy (arckit-oaa)
    "REPO",  # Repository (arckit-claude)
    "TRANS", # Transition architecture (arckit-togaf-adm)
}


def _doc_type_codes(d: dict) -> list[str]:
    return list(d.keys())


class TestIntakeTableShape:
    def test_intake_is_dict(self):
        assert isinstance(INTAKE, dict)

    def test_intake_codes_are_doc_type_format(self):
        bad = [c for c in _doc_type_codes(INTAKE) if not _DOC_TYPE_RE.match(c)]
        assert bad == [], f"malformed doc-type codes in INTAKE: {bad}"

    def test_intake_entries_well_formed(self):
        for code, entry in INTAKE.items():
            assert isinstance(entry, dict), f"{code}: entry is not a dict"
            questions = entry.get("questions")
            assert isinstance(questions, list) and questions, (
                f"{code}: questions must be a non-empty list"
            )
            for q in questions:
                assert isinstance(q, str) and q.strip(), (
                    f"{code}: question item {q!r} is not a non-empty string"
                )
            mandatory = entry.get("mandatory_inputs", [])
            assert isinstance(mandatory, list), f"{code}: mandatory_inputs not a list"
            for mi in mandatory:
                assert _DOC_TYPE_RE.match(mi), (
                    f"{code}: mandatory_input {mi!r} is not a 4-char uppercase code"
                )
            source = entry.get("source", "")
            assert isinstance(source, str) and source.endswith(".md"), (
                f"{code}: source {source!r} must be a .md path"
            )

    def test_minimum_intake_codes_present(self):
        missing = _MINIMUM_INTAKE_CODES - set(INTAKE)
        assert not missing, f"codes that lost coverage after a regeneration: {sorted(missing)}"


class TestCoverageTableShape:
    def test_coverage_is_dict(self):
        assert isinstance(COVERAGE, dict)

    def test_coverage_codes_are_doc_type_format(self):
        bad = [c for c in _doc_type_codes(COVERAGE) if not _DOC_TYPE_RE.match(c)]
        assert bad == [], f"malformed doc-type codes in COVERAGE: {bad}"

    def test_coverage_statuses_closed_set(self):
        allowed = {"covered", "no-static-questions"}
        bad = {c: v for c, v in COVERAGE.items() if v not in allowed}
        assert not bad, f"COVERAGE statuses outside {sorted(allowed)}: {bad}"

    def test_no_duplicate_codes(self):
        assert len(COVERAGE) == len(set(COVERAGE))
        assert len(INTAKE) == len(set(INTAKE))


class TestCoverageDrift:
    def test_intake_codes_are_subset_of_coverage(self):
        extra = set(INTAKE) - set(COVERAGE)
        assert not extra, f"INTAKE codes missing from COVERAGE: {sorted(extra)}"

    def test_covered_set_equals_intake_set(self):
        covered = {c for c, v in COVERAGE.items() if v == "covered"}
        assert covered == set(INTAKE), (
            "COVERAGE/INTAKE drift — a code is marked covered without intake "
            f"data (or vice versa). covered-but-missing: "
            f"{sorted(covered - set(INTAKE))}; "
            f"intake-but-not-covered: {sorted(set(INTAKE) - covered)}"
        )


class TestIntakePayloadRendering:
    """The MCP payload renders ``questions`` as a flat list of lines.

    For templates whose intake block lists multiple-choice options on
    lines following the question, the generator appends the option
    strings to the same list (no nesting). ``GAPS`` and ``TRANS``
    both hit this path; pin the shape so a restructuring fails here.
    """

    def test_multi_option_questions_are_flat(self):
        # Both codes carry option items (e.g. "Balanced", "2 waves")
        # as plain list entries after their question text.
        for code in ("GAPS", "TRANS"):
            questions = INTAKE[code]["questions"]
            assert isinstance(questions, list)
            assert all(isinstance(q, str) for q in questions), (
                f"{code}: nested option structures would break the flat payload"
            )

    def test_known_options_present(self):
        gaps = INTAKE["GAPS"]["questions"]
        assert any("Balanced" in q for q in gaps)
        trans = INTAKE["TRANS"]["questions"]
        assert any("waves" in q for q in trans)


class TestParserNotes:
    """PARSER_NOTES is comment-only (no runtime binding).

    The module docstring says unresolved templates are listed as
    comments; assert no executable PARSER_NOTES symbol exists, so a
    future edit that turns it into data (a dict, a list, anything)
    is caught here rather than silently changing the module surface.
    """

    def test_no_parser_notes_binding(self):
        import arckit_mcp.intake as intake_module

        assert not hasattr(intake_module, "PARSER_NOTES"), (
            "PARSER_NOTES must remain comment-only; a runtime binding "
            "would change the module's public surface"
        )
